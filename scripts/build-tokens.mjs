// Generates src/styles/tokens.css from knowledge/01-design/design-tokens.json.
// `--check` exits 1 when the committed file is stale (used in CI).
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const src = fileURLToPath(new URL('../design/design-tokens.json', import.meta.url))
const out = fileURLToPath(new URL('../app/assets/css/tokens.css', import.meta.url))
const tokens = JSON.parse(readFileSync(src, 'utf8'))

const lookup = (path) => path.split('.').reduce((node, key) => node[key], tokens)
const resolve = (value) => {
  const ref = typeof value === 'string' && value.match(/^\{(.+)\}$/)
  return ref ? resolve(lookup(ref[1]).$value) : value
}

const lines = []
const walk = (node, path) => {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    if (child && typeof child === 'object' && '$value' in child) {
      lines.push(`  --sx-${[...path, key].join('-')}: ${resolve(child.$value)};`)
    } else if (child && typeof child === 'object') {
      walk(child, [...path, key])
    }
  }
}
walk(tokens, [])

const css = `/* Generated by scripts/build-tokens.mjs from design/design-tokens.json (copied from ScanAxe knowledge). Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== css) {
    console.error('tokens.css is stale: run `npm run tokens`')
    process.exit(1)
  }
  console.log('tokens.css is up to date')
} else {
  writeFileSync(out, css)
  console.log(`wrote ${lines.length} tokens`)
}
